"""Regenerates js/ink-glyphs.js (single-stroke cursive pen paths for The Ink Within) from the public-domain Hershey 'Script Simplex' font.
Only needed if you want a different handwriting font.  pip install Hershey-Fonts  then:  python3 tools/make_ink_glyphs.py"""
import json, os
from HersheyFonts import HersheyFonts
FONT = 'scripts'          # try 'scriptc' (more ornate) or 'cursive'
g = HersheyFonts(); g.load_default_font(FONT); out = {}
for c in range(32, 127):
    gl = g.all_glyphs.get(chr(c))
    if not gl: continue
    L, R = gl._HersheyGlyph__left_side, gl._HersheyGlyph__right_side
    out[chr(c)] = [R - L, [[v for x, y in st for v in (x - L, y)] for st in gl._HersheyGlyph__strokes]]
js = ("/* ink-glyphs.js - single-stroke cursive pen paths (Hershey 'Script Simplex', public domain) used by The Ink Within.\n"
      "   Each glyph: [advance, [stroke, ...]] where a stroke is x,y,x,y,... in font units (baseline y=9, cap line y=-12, descender y=21).\n"
      "   Generated by tools/make_ink_glyphs.py - you normally never need to edit this file. */\n"
      "window.INK_GLYPHS = " + json.dumps({'baseline': 9, 'cap': -12, 'desc': 21, 'g': out}, separators=(',', ':')) + ";\n")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'ink-glyphs.js'), 'w').write(js)
